"""Evaluate trained AlphaZero policies.

Three modes:
  - self-play: trained solver vs trained stacker (the headline metric).
  - vs random stacker: how often does the trained solver clear puzzles
    generated by uniform random placement? (Tests raw solver competence.)
  - vs random solver: how often does the trained stacker block a solver
    that takes uniform random legal actions? (Tests raw stacker adversariality.)

Run via:
  python eval_alphazero.py checkpoint=outputs/alphazero/alphazero_latest.pt \
                           n_episodes=64 mode=all
"""

