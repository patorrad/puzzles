class UniformNet(nn.Module):
    """Returns uniform-zero logits and zero value. Used as a non-learning baseline.

    With zero logits, masked_softmax produces a uniform distribution over legal
    actions, so MCTS guided by this net behaves like uninformed PUCT.
    """

    def __init__(self, n_actions: int):
        super().__init__()
        self.n_actions = n_actions
        # Dummy parameter so .to(device) and .eval() work without errors.
        self._dummy = nn.Parameter(torch.zeros(1), requires_grad=False)

    def forward(self, x: torch.Tensor):
        if x.dim() == 1:
            B = 1
        else:
            B = x.shape[0]
        logits = torch.zeros(B, self.n_actions, device=x.device if x.is_cuda else 'cpu')
        value = torch.zeros(B, device=logits.device)
        return logits, value


@dataclass
class EvalResults:
    n_episodes: int
    solver_wins: int
    stacker_wins: int
    avg_solver_steps: float

    @property
    def solver_win_rate(self) -> float:
        return self.solver_wins / max(self.n_episodes, 1)

    @property
    def stacker_win_rate(self) -> float:
        return self.stacker_wins / max(self.n_episodes, 1)

    def summary(self) -> str:
        return (f'episodes={self.n_episodes}  '
                f'solver_win={self.solver_win_rate:.3f}  '
                f'stacker_win={self.stacker_win_rate:.3f}  '
                f'avg_solver_steps={self.avg_solver_steps:.2f}')


def _settle(env, n_steps: int):
    step_fn = getattr(env, '_step_sim', None)
    if step_fn is None:
        return
    for _ in range(n_steps):
        try:
            step_fn(render=False)
        except TypeError:
            step_fn()


def _sample_random_target_cell(spec: GridSpec, rng: random.Random) -> tuple[int, int]:
    i = rng.randrange(spec.Gx)
    j = rng.randrange(max(1, spec.Gy // 2), spec.Gy)
    return i, j


def _random_stacker_placement(spec: GridSpec, target_cell: tuple[int, int],
                              n_obstacles: int, rng: random.Random
                              ) -> list[tuple[int, int, int]]:
    """Uniform random legal placement. Skips MCTS entirely."""
    occupied = torch.zeros(spec.Gx, spec.Gy, spec.Z, dtype=torch.int8)
    placed: list[tuple[int, int, int]] = []
    ti, tj = target_cell
    for _ in range(n_obstacles):
        legal: list[tuple[int, int, int]] = []
        for i in range(spec.Gx):
            for j in range(spec.Gy):
                for k in range(spec.Z):
                    if occupied[i, j, k]:
                        continue
                    if k > 0 and not occupied[i, j, k - 1]:
                        continue
                    if k == 0 and (i, j) == (ti, tj):
                        continue
                    legal.append((i, j, k))
        if not legal:
            break
        ijk = rng.choice(legal)
        placed.append(ijk)
        occupied[ijk] = 1
    return placed


def _trained_stacker_placement(env, stacker_net, spec, target_cell, sp_cfg, device,
                               n_obstacles: int) -> list[tuple[int, int, int]]:
    """Greedy MCTS-guided placement using the trained stacker."""
    game = StackerGame(spec, n_obstacles)
    mcts = AZMCTS(game, stacker_net, c_puct=sp_cfg.c_puct, dirichlet_eps=0.0,
                  device=device)
    state = game.initial_state(target_cell)
    placed: list[tuple[int, int, int]] = []
    for _ in range(n_obstacles):
        _, counts = mcts.run(state, sp_cfg.n_simulations_stacker, add_root_noise=False)
        if counts.sum() <= 0:
            break
        a = int(counts.argmax().item())
        ijk = spec.unflatten(a)
        placed.append(ijk)
        state = state.with_placement(*ijk)
    return placed


def evaluate(env, solver_net, stacker_net, spec: GridSpec, sp_cfg: SelfPlayConfig,
             n_episodes: int, device: str = 'cpu',
             random_stacker: bool = False, random_solver: bool = False,
             seed: int = 0, render: bool = False,
             pause_between_eps: bool = False) -> EvalResults:
    """Run n_episodes deterministic (argmax) evaluation games.

    Episodes are processed in batches of ``min(env.n_envs, remaining)`` so the
    env's parallelism is used. Each step within an episode uses a single MCTS
    run with zero Dirichlet noise and temperature 0 (argmax) — eval should be
    deterministic given the seed.

    When ``render=True``, ``env.show_viewer`` is toggled so that physics
    rendering happens only while the chosen action is being executed (not
    during MCTS leaf evaluations). Pair with parallel_envs=1 for clean replay.
    """
    rng = random.Random(seed)
    n_obstacles = env.n_obstacles
    solver_game = SolverGame(env, spec, max_depth=sp_cfg.max_depth)

    solver_wins = 0
    stacker_wins = 0
    total_steps = 0
    eps_played = 0

    # When rendering: hide MCTS-internal physics noise (env.show_viewer=False)
    # except during chosen-action execution and stacker realize/settle.
    prev_show = getattr(env, 'show_viewer', False)
    if render:
        env.show_viewer = False

    def _set_render(on: bool):
        if render:
            env.show_viewer = bool(on)

    while eps_played < n_episodes:
        K = min(env.n_envs, n_episodes - eps_played)

        # --- Stacker phase ---
        target_cells = [_sample_random_target_cell(spec, rng) for _ in range(K)]
        placed_lists: list[list[tuple[int, int, int]]] = []
        for i in range(K):
            if random_stacker:
                placed = _random_stacker_placement(spec, target_cells[i],
                                                   n_obstacles, rng)
            else:
                placed = _trained_stacker_placement(
                    env, stacker_net, spec, target_cells[i], sp_cfg, device, n_obstacles)
            placed_lists.append(placed)

        # Realize K initial states into K env slots
        init_states = [realize_state(spec, placed_lists[i], target_cells[i], env._OBJ_SIZE)
                       for i in range(K)]
        _set_render(True)   # show puzzle being placed
        for i, s in enumerate(init_states):
            env.set_state(s, env_idx=i)
        _settle(env, sp_cfg.settle_steps)
        _set_render(False)  # MCTS rollouts coming up — quiet the viewer
        env_states = [env.get_state(i) for i in range(K)]

        # --- Solver phase ---
        states = [solver_game.initial_state(es) for es in env_states]
        finished = [solver_game.is_terminal(s) for s in states]
        final_states = list(states)
        steps_per_ep = [0] * K

        for _turn in range(sp_cfg.max_depth):
            active = [i for i in range(K) if not finished[i]]
            if not active:
                break

            if random_solver:
                # Uniform random over all 4*(N+1)*Z actions (all legal for solver).
                chosen = [rng.randrange(solver_game.n_actions) for _ in active]
            else:
                results = run_parallel(solver_game, solver_net,
                                       [states[i] for i in active],
                                       n_simulations=sp_cfg.n_simulations_solver,
                                       c_puct=sp_cfg.c_puct, dirichlet_eps=0.0,
                                       add_root_noise=False, device=device)
                chosen = []
                for idx, i in enumerate(active):
                    _, counts = results[idx]
                    if counts.sum() <= 0:
                        chosen.append(rng.randrange(solver_game.n_actions))
                    else:
                        chosen.append(int(counts.argmax().item()))

            _set_render(True)   # render the actually-executed action
            new_results = solver_game.batched_transition(
                [states[i] for i in active], chosen)
            _set_render(False)
            for idx, i in enumerate(active):
                next_state, terminal = new_results[idx]
                states[i] = next_state
                final_states[i] = next_state
                steps_per_ep[i] += 1
                if terminal:
                    finished[i] = True

        for i in range(K):
            won = bool(env._is_goal(final_states[i]['env_state']))
            if won:
                solver_wins += 1
            else:
                stacker_wins += 1
            total_steps += steps_per_ep[i]

        eps_played += K
        logger.info('  ... %d/%d episodes done | running solver_win=%.3f',
                    eps_played, n_episodes, solver_wins / max(eps_played, 1))

        if render and pause_between_eps and eps_played < n_episodes:
            wait = getattr(env, 'wait_for_input', None)
            try:
                if wait is not None:
                    wait('  [Episode finished. Press Enter for next...]')
                else:
                    input('  [Episode finished. Press Enter for next...]')
            except EOFError:
                break

    if render:
        env.show_viewer = prev_show

    return EvalResults(
        n_episodes=eps_played,
        solver_wins=solver_wins,
        stacker_wins=stacker_wins,
        avg_solver_steps=total_steps / max(eps_played, 1),
    )


def load_checkpoint(path: str) -> tuple[SolverNet, StackerNet, GridSpec]:
    ckpt = torch.load(path, map_location='cpu', weights_only=False)
    solver = SolverNet(in_dim=ckpt['solver_in_dim'],
                       n_actions=ckpt['solver_n_actions'])
    solver.load_state_dict(ckpt['solver'])
    solver.eval()
    stacker = StackerNet(grid_h=ckpt['stacker_grid_h'],
                         grid_w=ckpt['stacker_grid_w'],
                         n_actions=ckpt['stacker_n_actions'])
    stacker.load_state_dict(ckpt['stacker'])
    stacker.eval()
    spec = GridSpec(**ckpt['spec'])
    return solver, stacker, spec
